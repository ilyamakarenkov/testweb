    // Не вставляем демо-новости, если на сайте уже есть 20 и больше
    $stmt = $pdo->query('SELECT COUNT(*) AS c FROM news');
    $row = $stmt->fetch();
    $total = isset($row['c']) ? (int) $row['c'] : 0;
    if ($total >= 20) {
        $setFlag->execute();
        return;
    }

    $existingStmt = $pdo->query('SELECT title FROM news');
    $existing = array();
    while ($r = $existingStmt->fetch()) {
        $existing[] = mb_strtolower($r['title'], 'UTF-8');
    }

    $ins = $pdo->prepare("INSERT INTO news (title, slug, excerpt, content, image, is_published, published_at)
        VALUES (:title, :slug, :excerpt, :content, NULL, 1, :date)");
