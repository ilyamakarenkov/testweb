        if (in_array($low, $existing, true)) {
            continue;
        }
        $ins->execute(array(
            ':title' => $s['title'],
            ':slug' => slugify($s['title']),
            ':excerpt' => $s['excerpt'],
            ':content' => $s['content'],
            ':date' => date('Y-m-d H:i:s', strtotime('-' . (int) $s['d'] . ' days')),
        ));
        $existing[] = $low;
